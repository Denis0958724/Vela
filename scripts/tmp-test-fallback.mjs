const port = process.argv[2] ?? '9329';
const expression = process.argv[3] ?? '1';
const targets = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const page = targets.find(t => t.type === 'page' && t.title === 'Vela') ?? targets.find(t => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let seq = 0; const waiting = new Map();
const call = (method, params={}) => new Promise((resolve,reject)=>{const id=++seq;waiting.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
ws.addEventListener('message', e=>{const msg=JSON.parse(e.data);const s=waiting.get(msg.id);if(!s)return;waiting.delete(msg.id);msg.error?s.reject(new Error(msg.error.message)):s.resolve(msg.result);});
await new Promise((resolve,reject)=>{ws.addEventListener('open',resolve,{once:true});ws.addEventListener('error',reject,{once:true});});
const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true,userGesture:true});
console.log(JSON.stringify(r.result?.value??null));
process.exit(0);
